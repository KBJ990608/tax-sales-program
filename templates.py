def template_names() -> list[str]:
    return list(TEMPLATES.keys())


def _fill(text: str, company: str, ceo: str) -> str:
    """{업체명}/{대표자}만 치환한다. (그 외 중괄호는 그대로 두어 KeyError 방지)"""
    return text.replace("{업체명}", company).replace("{대표자}", ceo)


def render(template_name: str, company: str, ceo: str) -> tuple[str, str]:
    """고정 템플릿을 실제 값으로 치환해 (제목, 본문) 반환. 대표자 없으면 '대표'."""
    company = (company or "").strip() or "사장님"
    ceo = (ceo or "").strip() or "대표"
    t = TEMPLATES[template_name]
    return _fill(t["제목"], company, ceo), _fill(t["본문"], company, ceo)


def render_raw(subject_tmpl: str, body_tmpl: str, company: str, ceo: str) -> tuple[str, str]:
    """AI가 생성한 임의 템플릿 문자열을 치환해 (제목, 본문) 반환."""
    company = (company or "").strip() or "사장님"
    ceo = (ceo or "").strip() or "대표"
    return _fill(subject_tmpl, company, ceo), _fill(body_tmpl, company, ceo)
